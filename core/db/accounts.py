def update_account_registration_password(acc_id: int, password: str) -> bool:
    """更新账号的 OpenAI 登录/注册密码 (registration_password)。"""
    pwd = str(password or "").strip()
    if not pwd:
        return False
    _ensure_sqlite()
    now_str = _now()
    with _LOCK, closing(_sqlite_conn()) as conn:
        with conn:
            cur = conn.execute(
                """
                UPDATE registered_accounts
                SET updated_at = ?,
                    payload = json_set(
                        CASE WHEN payload IS NULL OR payload='' THEN '{}' ELSE payload END,
                        '$.registration_password', ?,
                        '$.password', ?,
                        '$.updated_at', ?
                    )
                WHERE id = ?
                RETURNING payload
                """,
                (now_str, pwd, pwd, now_str, int(acc_id)),
            )
            row_db = cur.fetchone()
            if not row_db:
                return False
            try:
                row = json.loads(row_db["payload"]) if row_db["payload"] else {}
            except Exception:
                row = {}

        # 密码更新后，自动向 gptGrok2api 同步最新 login_password
        try:
            from core.gptgrok2api_sync import _extract_account_info, push_accounts_to_gptgrok2api
            info = _extract_account_info(row)
            if info.get("email"):
                push_accounts_to_gptgrok2api([info])
        except Exception:
            pass

        return True


